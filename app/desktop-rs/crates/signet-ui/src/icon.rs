impl IconNamed for IconName {
    fn path(self) -> SharedString {
        self.asset_path().into()
    }
}

/// An icon of `size` px in `color` (the stroke follows the text color).
pub fn icon(name: IconName, size: impl Into<Pixels>, color: impl Into<Hsla>) -> impl IntoElement {
    Icon::from(name).size(size.into()).text_color(color.into())
}
